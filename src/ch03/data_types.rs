fn main() {
    /*
    Scalar Type -> 하나의 값으로 표현되는 타입
    Rust는 정수형(i8, ..., u64, isize, usize), 부동소수점 숫자(f32, f64), `bool`, 그리고 `char`, 네 가지 스칼라 타입을 보유하고 있습니다.
    */
    let _x: i8 = 5;
    let _y = 3.0;
    let _t = true;
    let _z: char = 'z';

    /*
    Composite Type -> 다른 타입의 다양한 값들을 하나의 타입으로 묶은 타입
    Rust는 튜플과 배열 두 개의 기본 타입들을 갖고 있다.
    */
    // 튜플 -> 다양한 타입의 몇 개의 값을 하나의 복합 타입으로 만드는 일반적인 방법
    // 튜플은 단일 요소를 위한 복합계로 고려되었기에 변수 tup에는 튜플 전체가 bind 됩니다.
    let tup: (i32, f64, u8) = (500, 6.4, 1);
    // 개별 값을 튜플의 밖으로 빼내오기 위해서는, 패턴 매칭을 사용하여 튜플의 값을 구조분해 시키면 됩니다.
    let (a, b, c) = tup;
    println!("a: {a}, b: {b}, c: {c}");
    // 패턴 매칭을 통한 구조분해 뿐만 아니라 마침표('.') 뒤에 접근하길 원하는 값의 색인을 넣는 것을 통해 튜플의 요소에 직접 접근 가능
    let five_hundred = tup.0;
    let six_point_four = tup.1;
    let one = tup.2;
    println!("five_hundred: {five_hundred}, six_point_four: {six_point_four}, one: {one}");

    // 배열 -> 같은 타입의 몇 개의 값을 하나의 복합 타입으로 만드는 일반적인 방법
    // 튜플과는 다르게, 배열의 모든 요소는 모두 같은 타입이여야 합니다.
    // Rust에서 배열은 고정된 길이를 가지므로 한번 선언되면, 이들은 크기는 커지거나 작아지지 않습니다.
    // 배열이 유용할 때는 데이터를 힙보다 스택에 할당하는 것을 원하거나, 항상 고정된 숫자의 요소를 갖는다고 확신하고 싶을 때입니다.
    let arr = [1, 2, 3, 4, 5];
    // 벡터 타입은 유사 집합체로 표준 라이브러리에서 제공되며 확장 혹은 축소가 가능합니다.
    // 배열이나 벡터 중에 뭘 선택해야 할지 확실하지 않은 상황이라면 벡터를 사용하도록 하세요
    // 배열은 stack에 단일 메모리 뭉치로 할당됩니다. 우리는 색인을 통해 배열의 요소에 접근할 수 있습니다.
    println!("arr[0]: {}", arr[0]);
}